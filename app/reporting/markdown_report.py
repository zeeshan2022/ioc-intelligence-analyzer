"""Markdown report renderer (ticket/case-management friendly)."""

from __future__ import annotations

from pathlib import Path

from app.core.models import AnalysisResult, BulkAnalysisReport
from app.reporting.utils import build_filename, ensure_output_dir, write_text_atomic


def render_markdown(result: AnalysisResult) -> str:
    """Render a single-IOC analyst report as Markdown."""
    data = result.to_dict()
    risk = data["risk"]
    summary = data["analyst_summary"]
    ioc = data["ioc"]

    lines: list[str] = []
    lines.append(f"# IOC Intelligence Report - `{ioc['value']}`")
    lines.append("")
    lines.append(f"- **Analysis ID:** `{result.analysis_id}`")
    lines.append(f"- **Generated (UTC):** {result.generated_at}")
    lines.append(f"- **Tool version:** {result.tool_version}")
    lines.append(f"- **IOC type:** {ioc['ioc_type']}")
    lines.append(f"- **Risk score:** **{risk['score']}/100** ({risk['level'].upper()})")
    lines.append("")

    lines += ["## Executive Summary", "", summary["executive_summary"], ""]
    lines += ["## Threat Assessment", "", summary["threat_assessment"], ""]

    lines += ["## Risk Score Breakdown", "", "| Factor | Points | Explanation |", "|---|---:|---|"]
    for factor in risk["factors"]:
        safe_expl = factor["explanation"].replace("|", "\\|")
        lines.append(f"| {factor['name']} | {factor['points']:+d} | {safe_expl} |")
    if not risk["factors"]:
        lines.append("| _no signals_ | 0 | No provider signal contributed |")
    lines.append("")
    lines += ["> " + risk["explanation"], ""]

    lines += ["## Provider Findings", "", "| Provider | Status | Confidence | Verdict | Summary |", "|---|---|---:|---|---|"]
    for enr in data["enrichments"]:
        verdict = {True: "MALICIOUS", False: "BENIGN", None: "-"}[enr.get("malicious")]
        safe_sum = str(enr["summary"]).replace("|", "\\|")
        lines.append(f"| {enr['provider']} | {enr['status']} | {enr['confidence']} | {verdict} | {safe_sum} |")
    lines.append("")

    lines += ["## Observed Activity", ""]
    for item in summary["observed_activity"]:
        lines.append(f"- {item}")
    lines.append("")

    lines += ["## MITRE ATT&CK Mapping", ""]
    if summary["mitre_techniques"]:
        lines += ["| Tactic | Technique | Rationale |", "|---|---|---|"]
        for tech in summary["mitre_techniques"]:
            lines.append(
                f"| {tech['tactic']} | {tech['technique_id']} - {tech['technique_name']} | {tech['rationale']} |"
            )
    else:
        lines.append("_No defensible ATT&CK mapping derived from current evidence._")
    lines.append("")

    lines += ["## Recommended Actions", ""]
    lines += [f"{i}. {a}" for i, a in enumerate(summary["recommended_actions"], 1)]
    lines.append("")
    lines += ["## Containment Recommendations", ""]
    lines += [f"- {c}" for c in summary["containment_recommendations"]]
    lines.append("")
    lines += ["## Escalation Guidance", "", summary["escalation_guidance"], ""]
    lines += ["---", "_Generated by ioc-intelligence-analyzer. Verify with primary telemetry before enforcement._"]
    return "\n".join(lines) + "\n"


def render_bulk_markdown(report: BulkAnalysisReport) -> str:
    parts = [
        "# Bulk IOC Intelligence Report",
        "",
        f"- **Report ID:** `{report.report_id}`",
        f"- **Generated (UTC):** {report.generated_at}",
        f"- **Analysed:** {len(report.results)} · **Rejected inputs:** {len(report.invalid_inputs)}",
        "",
    ]
    if report.invalid_inputs:
        parts += ["## Rejected Inputs", ""]
        parts += [f"- `{inv.value}` - {inv.reason}" for inv in report.invalid_inputs]
        parts.append("")
    for res in report.results:
        parts.append(render_markdown(res))
    return "\n".join(parts)


def write_markdown(
    result: AnalysisResult | BulkAnalysisReport,
    output_dir: Path,
    filename: str | None = None,
) -> Path:
    out_dir = ensure_output_dir(Path(output_dir))
    if isinstance(result, BulkAnalysisReport):
        content = render_bulk_markdown(result)
        name = filename or f"bulk_{result.report_id[:8]}_report.md"
    else:
        content = render_markdown(result)
        name = filename or build_filename(result.ioc, "md")
    path = out_dir / name
    return write_text_atomic(path, content)
